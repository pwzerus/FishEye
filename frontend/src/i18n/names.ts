/** "Channel Catfish" → "channel-catfish", the key the guides use. */
export function fishSlug(commonName: string): string {
  return commonName.trim().toLowerCase().replace(/\s+/g, "-");
}

/** A fish's name in this language, or null in English or for a fish
 * without one there. */
