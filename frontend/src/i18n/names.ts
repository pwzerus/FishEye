/** "Channel Catfish" → "channel-catfish", the key the guides use. */
export function fishSlug(commonName: string): string {
  return commonName.trim().toLowerCase().replace(/\s+/g, "-");
}

/** A fish's name in this language, or null in English or for a fish
 * without one there. */
export function localFishName(slug: string, locale: Locale): string | null {
  return locale === "en" ? null : (FISH_NAMES[locale][slug] ?? null);
}

export function localTopicTitle(id: string, locale: Locale): string | null {
  return locale === "en" ? null : (HANDBOOK_TITLES[locale][id] ?? null);
}

export function localCategory(id: string, locale: Locale): string | null {
  return locale === "en" ? null : (HANDBOOK_CATEGORIES[locale][id] ?? null);
}

/** The photo check's look-alike group ("a black bass") in this language;
 * the label as the server sent it in English or for a group not listed. */
export function localGroup(label: string, locale: Locale): string {
  if (locale === "en") return label;
  return GROUP_NAMES[locale][label.replace(/^an? /, "")] ?? label;
}

/** "a black bass" → "black bass", "una lobina" → "lobina", for a tag. */
export function withoutArticle(label: string): string {
  return label.replace(/^(an?|una?) /, "");
}

