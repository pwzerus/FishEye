/** A state's name in this language; `english` when there is none (or in English). */
export function localStateName(code: string | null | undefined, english: string, locale: Locale): string {
  if (locale === "en" || !code) return english;
  return STATE_NAMES[locale][code.toUpperCase()] ?? english;
}

/** A catch's fish in this language: by its guide slug, else by its English
 * label when that is a guide fish; otherwise the label as the angler wrote it. */
export function localSpecies(slug: string | null | undefined, label: string | null | undefined, locale: Locale): string | null {
  const local = slug ? localFishName(slug, locale) : label ? localFishName(fishSlug(label), locale) : null;
  return local ?? label ?? null;
}

